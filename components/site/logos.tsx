export function BrandIcon({
  name,
  size = 20,
  monochrome = true,
  hoverColor,
  className,
}: {
  name: string;
  size?: number;
  monochrome?: boolean;
  hoverColor?: string;
  className?: string;
}) {
  const mark = MARKS.find((m) => m.id === name || m.label === name);
  if (!mark) return null;

  const brand = hoverColor ?? mark.hex;

  if (mark.src) {
    return (
      // eslint-disable-next-line @next/next/no-img-element
      <img
        src={mark.src}
        alt=""
        aria-hidden
        width={size}
        height={size}
        className={cn("brand-icon", className)}
        style={{ ["--brand" as string]: brand }}
      />
    );
  }

  return (
    <svg
      role="img"
      aria-hidden
      focusable="false"
      viewBox="0 0 24 24"
      width={size}
      height={size}
      fill="currentColor"
      className={cn("brand-icon", className)}
      style={{ ["--brand" as string]: monochrome ? brand : undefined, color: monochrome ? undefined : brand }}
    >
      <path d={mark.path} />
    </svg>
  );
}

export const AVAILABLE_MARKS = MARKS.filter((m) => m.status === "available");
export const SOON_MARKS = MARKS.filter((m) => m.status === "soon");
